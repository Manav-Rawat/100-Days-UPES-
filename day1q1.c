//Write a program to input two numbers and display their sum.


#include <stdio.h>
int main() {
    int a, b, c, d, e, f;
    a = 5;
    b = 10;
    c = a+b;
    d = a*b;
    e = a-b;
    f = a/b;
    printf("the value of c is %d\n", c);
    printf("the value of d is %d\n", d);
    printf("the value of e is %d\n", e);
    printf("the value of f is %d\n", f);
    return 0;
}   